"""Evaluation test support: shared helpers and an automatic test report.

Every test carries a docstring with `Input:` and `Expected:` lines. After a run the hook below
writes tests/evaluation/report/test_report.md and .json with name, input, expected, actual
(the real outcome and assertion message), pass/fail and a failure explanation.
"""

from __future__ import annotations

import json
import re
import time
from pathlib import Path

import pytest
from fastapi.testclient import TestClient

from src.live.agent import TaskManager
from src.live.api import create_app
from src.live.config import Settings
from tests.test_live_agent import FakeOllama, plan

FIXTURES = Path(__file__).parent / "fixtures"
REPORT_DIR = Path(__file__).parent / "report"
_results: list[dict] = []


@pytest.fixture
def settings(tmp_path: Path) -> Settings:
    ws = tmp_path / "ws"
    ws.mkdir()
    return Settings(workspace=ws, approval_timeout=5.0)


def ui_verdict(a: dict) -> str:
    """What the UNCHANGED frontend shows for an assessment (mirrors agent.ts)."""
    if a["status"] == "NOT_EVALUABLE":
        return "NOT_EVALUABLE"
    return "SENSITIVE" if a["is_sensitive"] else "CLEAN"


def wait_done(c: TestClient, tid: str, timeout: float = 10.0) -> dict:
    t0 = time.time()
    while time.time() - t0 < timeout:
        snap = c.get(f"/api/tasks/{tid}").json()
        if snap["status"] in ("completed", "failed"):
            return snap
        time.sleep(0.03)
    raise TimeoutError(snap)


def run_task(settings: Settings, name: str, data: bytes, fake: FakeOllama | None = None, instruction: str = "Summarize this document.") -> dict:
    """Upload one file and run a whole task through the real API; returns the final snapshot."""
    fake = fake or FakeOllama(settings, plans=[plan()], answer="A short summary.")
    c = TestClient(create_app(TaskManager(settings, fake)))
    fid = c.post("/api/upload", files=[("files", (name, data, "application/octet-stream"))]).json()["files"][0]["file_id"]
    tid = c.post("/api/tasks", json={"instruction": instruction, "file_ids": [fid]}).json()["task_id"]
    snap = wait_done(c, tid)
    snap["_fake"] = fake
    return snap


def fixture_bytes(name: str) -> bytes:
    return (FIXTURES / name).read_bytes()


# ---------------------------------------------------------------- report hook
@pytest.hookimpl(hookwrapper=True)
def pytest_runtest_makereport(item, call):
    outcome = yield
    rep = outcome.get_result()
    if rep.when == "call" or (rep.when == "setup" and rep.outcome != "passed"):
        doc = (item.function.__doc__ or "").strip()
        inp = re.search(r"Input:\s*(.+?)(?:\n\s*Expected:|\Z)", doc, re.S)
        exp = re.search(r"Expected:\s*(.+)", doc, re.S)
        msg = ""
        if rep.failed:
            msg = rep.longreprtext.strip().splitlines()[-1][:300] if rep.longreprtext else "setup/teardown error"
        _results.append({
            "name": item.nodeid.split("::", 1)[1],
            "input": " ".join(inp.group(1).split()) if inp else "(see test)",
            "expected": " ".join(exp.group(1).split()) if exp else "(see test)",
            "actual": "behaviour matched expectation" if rep.passed else f"{rep.outcome.upper()}: {msg}",
            "result": "PASS" if rep.passed else "FAIL",
            "failure_explanation": "" if rep.passed else msg,
        })


def pytest_sessionfinish(session, exitstatus):
    if not _results:
        return
    REPORT_DIR.mkdir(exist_ok=True)
    (REPORT_DIR / "test_report.json").write_text(json.dumps(_results, indent=1), encoding="utf-8")
    ok = sum(r["result"] == "PASS" for r in _results)
    lines = [f"# Evaluation test report\n\nGenerated by the last run: {ok}/{len(_results)} passed.\n",
             "| Test | Input | Expected | Actual | Result | Failure explanation |", "|---|---|---|---|---|---|"]
    esc = lambda s: s.replace("|", "\\|").replace("\n", " ")
    for r in _results:
        lines.append(f"| `{esc(r['name'])}` | {esc(r['input'])} | {esc(r['expected'])} | {esc(r['actual'])} | {r['result']} | {esc(r['failure_explanation'])} |")
    (REPORT_DIR / "test_report.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
